"""Search for a counterexample to Theorem 5.4 beyond the 3000 main instances.

A counterexample would be an instance that satisfies the Theorem 5.4 condition
but is NOT strategyproof (the Q2 situation).  The search uses the *weakest*
reading of the condition (odd simple paths, alpha != beta).  Every other reading
forbids at least as many pairs, so an instance that is clean under the weakest
reading is the hardest test of the theorem.

Two searches, both with self-attacks allowed and 3 agents:
  1. exhaustive: every attack relation on n arguments (2^(n*n) of them) times
     every assignment of the arguments to the 3 agents (3^n), for n = 1..N;
  2. random: R instances with n ~ U{3..9}, p ~ U[0.1, 0.5].

Usage:
    python experiments/stress_test.py                       # exhaustive n <= 4, 300000 random
    python experiments/stress_test.py --max-n 3 --random 20000
"""
from __future__ import annotations

import argparse
import json
import random
import sys
import time
from itertools import product
from multiprocessing import Pool
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from argengine.generators import random_instance  # noqa: E402
from argengine.strategic import SIMPLE, MechanismInstance  # noqa: E402

AGENTS = 3


def check(args, attacks, types) -> tuple[bool, bool]:
    """(condition holds under the weakest reading, strategyproof); SP is only
    computed when the condition holds, which is all the theorem needs."""
    m = MechanismInstance(args, attacks, types)
    if not m.theorem_5_4(SIMPLE, include_self=False).holds:
        return False, True
    return True, m.is_strategyproof().strategyproof


def exhaustive_chunk(job) -> tuple[int, int, int, list]:
    """All type assignments for attack masks in [lo, hi) on n arguments."""
    n, lo, hi = job
    args = tuple(f"a{k}" for k in range(1, n + 1))
    pairs = [(x, y) for x in args for y in args]
    owners_all = list(product(range(AGENTS), repeat=n))
    total = held = 0
    bad = []
    for mask in range(lo, hi):
        attacks = [pairs[i] for i in range(len(pairs)) if mask >> i & 1]
        for owners in owners_all:
            types = [frozenset(a for a, o in zip(args, owners) if o == i) for i in range(AGENTS)]
            total += 1
            cond, sp = check(args, attacks, types)
            if cond:
                held += 1
                if not sp:
                    bad.append({"arguments": args, "attacks": attacks, "types": [sorted(t) for t in types]})
    return total, held, len(bad), bad[:5]


def random_chunk(job) -> tuple[int, int, int, list]:
    seed, count = job
    rng = random.Random(seed)
    total = held = 0
    bad = []
    for _ in range(count):
        inst = random_instance(rng, rng.uniform(0.1, 0.5), (3, 9), AGENTS, allow_self_attacks=True)
        total += 1
        cond, sp = check(inst.arguments, inst.attacks, inst.types)
        if cond:
            held += 1
            if not sp:
                bad.append(inst.to_dict())
    return total, held, len(bad), bad[:5]


def run(pool, fn, jobs) -> dict:
    total = held = nbad = 0
    examples = []
    for t, h, b, ex in pool.imap_unordered(fn, jobs):
        total, held, nbad = total + t, held + h, nbad + b
        examples += ex
    return {"instances": total, "condition_holds": held, "counterexamples": nbad, "examples": examples[:5]}


def write_macros(result: dict, path: Path) -> None:
    """LaTeX macros with the counts, read by report/report.tex."""
    ex = result["exhaustive"].values()
    r = result["random"]
    tot = sum(e["instances"] for e in ex)
    vals = {
        "StressMaxN": max(map(int, result["exhaustive"])),
        "StressExTotal": tot, "StressExHeld": sum(e["condition_holds"] for e in ex),
        "StressExBad": sum(e["counterexamples"] for e in ex),
        "StressRandTotal": r["instances"], "StressRandHeld": r["condition_holds"], "StressRandBad": r["counterexamples"],
        "StressGrandTotal": 3000 + tot + r["instances"],   # + the 3000 main instances
    }
    fmt = lambda v: f"{v:,}".replace(",", "{,}")
    path.write_text("% generated by experiments/stress_test.py -- do not edit\n" +
                    "".join(f"\\newcommand{{\\{k}}}{{{fmt(v)}}}\n" for k, v in vals.items()))


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--max-n", type=int, default=4, help="exhaustive search for n = 1..max-n")
    ap.add_argument("--random", type=int, default=300_000, help="number of random instances")
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--out", type=Path, default=Path(__file__).parent / "results" / "stress_test.json")
    ap.add_argument("--macros", type=Path, default=Path(__file__).parents[1] / "report" / "stress_macros.tex")
    ap.add_argument("--macros-only", action="store_true", help="rewrite the macros from an existing --out file")
    a = ap.parse_args(argv)
    if a.macros_only:
        write_macros(json.loads(a.out.read_text()), a.macros)
        print(f"wrote {a.macros}")
        return

    result = {"agents": AGENTS, "reading": "odd simple path, alpha != beta (weakest)", "self_attacks": True}
    t0 = time.time()
    with Pool(a.workers) as pool:
        ex = {}
        for n in range(1, a.max_n + 1):
            masks = 1 << (n * n)
            step = max(1, masks // 256)
            ex[n] = run(pool, exhaustive_chunk, [(n, lo, min(lo + step, masks)) for lo in range(0, masks, step)])
            print(f"exhaustive n={n}: {ex[n]['instances']} instances, condition holds in "
                  f"{ex[n]['condition_holds']}, counterexamples {ex[n]['counterexamples']}  ({time.time() - t0:.0f}s)")
        result["exhaustive"] = ex
        chunk = 2000
        jobs = [(f"{a.seed}-stress-{k}", min(chunk, a.random - k * chunk)) for k in range(-(-a.random // chunk))]
        result["random"] = run(pool, random_chunk, jobs)
        result["random"].update({"n_range": [3, 9], "p_range": [0.1, 0.5], "seed": a.seed})
        r = result["random"]
        print(f"random: {r['instances']} instances, condition holds in {r['condition_holds']}, "
              f"counterexamples {r['counterexamples']}  ({time.time() - t0:.0f}s)")
    result["seconds"] = round(time.time() - t0, 1)
    a.out.write_text(json.dumps(result, indent=2))
    write_macros(json.loads(a.out.read_text()), a.macros)
    print(f"wrote {a.out} and {a.macros}")


if __name__ == "__main__":
    main()
